// Writes PowerEditor/src/MISC/Common/WindowsCodePages.h: what Windows' MultiByteToWideChar makes of the bytes 0x80 to 0xFF
// in each single-byte code page that Notepad++'s EncodingMapper can choose, so that the port reads and writes them as
// the original does, undefined bytes included (Windows maps those to private-use characters, which keeps them on save).
//
// Build with MinGW and run with Wine or Proton, whose tables come from Microsoft's:
//   x86_64-w64-mingw32-gcc -O2 -o winCodePages.exe cmake/tools/winCodePages.c
//   wine winCodePages.exe Z:\path\to\PowerEditor\src\MISC\Common\WindowsCodePages.h
#include <windows.h>
#include <stdio.h>

static const unsigned codePages[] = {
	437, 720, 737, 775, 850, 852, 855, 857, 858, 860, 861, 862, 863, 865, 866, 869, 874,
	1250, 1251, 1252, 1253, 1254, 1255, 1256, 1257, 1258,
	10007, 20866, 21866,
	28591, 28592, 28593, 28594, 28595, 28596, 28597, 28598, 28599, 28603, 28604, 28605
};

int main(int argc, char** argv)
{
	if (argc < 2)
		return 1;
	FILE* out = fopen(argv[1], "wb");
	if (!out)
		return 2;

	fprintf(out, "// Generated by cmake/tools/winCodePages.c from Windows' code page tables (through Wine): do not edit.\r\n");
	fprintf(out, "// For each single-byte code page, the characters of the bytes 0x80 to 0xFF. The bytes below are ASCII.\r\n\r\n");
	fprintf(out, "#pragma once\r\n\r\nstruct WindowsCodePage\r\n{\r\n\tunsigned codePage;\r\n\tchar16_t high[128];\r\n};\r\n\r\n");
	fprintf(out, "inline constexpr WindowsCodePage windowsCodePages[] = {\r\n");
	for (unsigned i = 0; i < sizeof(codePages) / sizeof(codePages[0]); ++i)
	{
		const unsigned cp = codePages[i];
		CPINFO info;
		if (!IsValidCodePage(cp) || !GetCPInfo(cp, &info) || info.MaxCharSize != 1)
		{
			fprintf(out, "\t// %u: not a single-byte code page here\r\n", cp);
			continue;
		}

		// ASCII is the same in all of them, which the codec relies on
		for (int b = 0; b < 0x80; ++b)
		{
			char byte = (char)b;
			WCHAR wc = 0;
			if (MultiByteToWideChar(cp, 0, &byte, 1, &wc, 1) != 1 || wc != b)
				fprintf(out, "\t// %u: byte 0x%02X is U+%04X, not ASCII\r\n", cp, b, wc);
		}

		fprintf(out, "\t{%u, {", cp);
		for (int b = 0x80; b < 0x100; ++b)
		{
			char byte = (char)b;
			WCHAR wc = 0xFFFD;
			if (MultiByteToWideChar(cp, 0, &byte, 1, &wc, 1) != 1)
				wc = 0xFFFD;
			if ((b & 15) == 0)
				fprintf(out, "\r\n\t\t");
			fprintf(out, "0x%04X,", wc);
		}
		fprintf(out, "\r\n\t}},\r\n");
	}
	fprintf(out, "};\r\n");
	fclose(out);
	return 0;
}
